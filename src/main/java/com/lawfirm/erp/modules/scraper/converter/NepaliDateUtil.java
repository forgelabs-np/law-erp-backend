    private static final int BASE_YEAR = 2000;
    private static final LocalDate EPOCH = LocalDate.of(1943, 4, 13);
    private static final Pattern BS_DATE = Pattern.compile("(\\d{4})-(\\d{2})-(\\d{2})");

    private NepaliDateUtil() {
    }

    /** "2083-05-01" (Arabic digits) -> AD LocalDate, or null when unparseable/out of range. */
    public static LocalDate bsToAd(String bsDate) {
        if (bsDate == null) return null;
        var m = BS_DATE.matcher(bsDate.trim());
        if (!m.matches()) return null;
        int year = Integer.parseInt(m.group(1));
        int month = Integer.parseInt(m.group(2));
        int day = Integer.parseInt(m.group(3));
        return bsToAd(year, month, day);
    }

    public static LocalDate bsToAd(int year, int month, int day) {
        if (year < BASE_YEAR || year > BASE_YEAR + MONTH_LENGTHS.length - 1) return null;
        int[] lengths = MONTH_LENGTHS[year - BASE_YEAR];
        if (month < 1 || month > 12 || day < 1 || day > lengths[month - 1]) return null;

        long daysPassed = day;
        for (int y = BASE_YEAR; y < year; y++) {
            daysPassed += sum(MONTH_LENGTHS[y - BASE_YEAR]);
        }
        for (int mo = 0; mo < month - 1; mo++) {
            daysPassed += lengths[mo];
        }
        return EPOCH.plusDays(daysPassed);
    }

    /** AD LocalDate -> "yyyy-mm-dd" BS string (Arabic digits), or null when out of range. */
    public static String adToBs(LocalDate ad) {
        if (ad == null) return null;
        long days = EPOCH.until(ad, java.time.temporal.ChronoUnit.DAYS);
        if (days < 1) return null;
        for (int i = 0; i < MONTH_LENGTHS.length; i++) {
            int total = sum(MONTH_LENGTHS[i]);
            if (days <= total) {
                int year = BASE_YEAR + i;
                int rem = (int) days;
                for (int mo = 0; mo < 12; mo++) {
                    int len = MONTH_LENGTHS[i][mo];
                    if (rem <= len) {
                        return String.format("%04d-%02d-%02d", year, mo + 1, rem);
                    }
                    rem -= len;
                }
            }
            days -= total;
        }
        return null;
    }

    private static int sum(int[] a) {
        int s = 0;
        for (int v : a) s += v;
        return s;
    }
